CREATE OR REPLACE FUNCTION "public"."match_schedule_events"("query_embedding" "public"."vector", "match_count" integer DEFAULT 3) RETURNS TABLE("id" "uuid", "event_date" "date", "start_time" time without time zone, "end_time" time without time zone, "activity_name" "text", "location" "text", "description" "text", "similarity" double precision)
    LANGUAGE "sql" STABLE
    AS $$
  select
    e.id,
    e.event_date,
    e.start_time,
    e.end_time,
    e.activity_name,
    e.location,
    e.description,
    1 - (e.embedding <=> query_embedding) as similarity
  from schedule_events e
  where e.embedding is not null
  order by e.embedding <=> query_embedding
  limit match_count;
$$;


ALTER FUNCTION "public"."match_schedule_events"("query_embedding" "public"."vector", "match_count" integer) OWNER TO "postgres";


CREATE OR REPLACE FUNCTION "public"."match_sessions"("query_embedding" "public"."vector", "match_count" integer DEFAULT 5) RETURNS TABLE("id" "uuid", "booth_number" integer, "tent_name" "text", "institution_name" "text", "activity_type" "public"."activity_type", "title" "text", "description" "text", "duration_minutes" integer, "age_label" "text", "session_date" "date", "similarity" double precision)
    LANGUAGE "sql" STABLE
    AS $$
  select
    s.id,
    b.booth_number,
    t.name_ar as tent_name,
    i.name as institution_name,
    s.activity_type,
    s.title,
    s.description,
    s.duration_minutes,
    s.age_label,
    s.session_date,
    1 - (s.embedding <=> query_embedding) as similarity
  from sessions s
  join booths b on b.id = s.booth_id
  left join tents t on t.id = b.tent_id
  join institutions i on i.id = s.institution_id
  where s.embedding is not null
  order by s.embedding <=> query_embedding
  limit match_count;
$$;


ALTER FUNCTION "public"."match_sessions"("query_embedding" "public"."vector", "match_count" integer) OWNER TO "postgres";


CREATE OR REPLACE FUNCTION "public"."rls_auto_enable"() RETURNS "event_trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO 'pg_catalog'
    AS $$
DECLARE
  cmd record;
BEGIN
  FOR cmd IN
    SELECT *
    FROM pg_event_trigger_ddl_commands()
    WHERE command_tag IN ('CREATE TABLE', 'CREATE TABLE AS', 'SELECT INTO')
      AND object_type IN ('table','partitioned table')
  LOOP
     IF cmd.schema_name IS NOT NULL AND cmd.schema_name IN ('public') AND cmd.schema_name NOT IN ('pg_catalog','information_schema') AND cmd.schema_name NOT LIKE 'pg_toast%' AND cmd.schema_name NOT LIKE 'pg_temp%' THEN
      BEGIN
        EXECUTE format('alter table if exists %s enable row level security', cmd.object_identity);
        RAISE LOG 'rls_auto_enable: enabled RLS on %', cmd.object_identity;
      EXCEPTION
        WHEN OTHERS THEN
          RAISE LOG 'rls_auto_enable: failed to enable RLS on %', cmd.object_identity;
      END;
     ELSE
        RAISE LOG 'rls_auto_enable: skip % (either system schema or not in enforced list: %.)', cmd.object_identity, cmd.schema_name;
     END IF;
  END LOOP;
END;
$$;


ALTER FUNCTION "public"."rls_auto_enable"() OWNER TO "postgres";


